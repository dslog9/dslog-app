<h1>Гемоглобин — норма, причины отклонений и что делать</h1>

<h2>Что это такое</h2>
<p>
Гемоглобин — это белок в крови, который переносит кислород от лёгких к тканям.
От его уровня зависит, насколько хорошо организм снабжается кислородом.
</p>

<h2>Норма</h2>
<ul>
    <li>Мужчины: 130–170 г/л</li>
    <li>Женщины: 120–150 г/л</li>
</ul>

<h2>Если повышен</h2>
<ul>
    <li>Обезвоживание</li>
    <li>Курение</li>
    <li>Хронические заболевания лёгких</li>
    <li>Заболевания крови</li>
</ul>

<h2>Если понижен</h2>
<ul>
    <li>Дефицит железа</li>
    <li>Кровопотеря</li>
    <li>Хронические заболевания</li>
    <li>Нехватка витамина B12</li>
</ul>

<h2>Риски</h2>
<p>
Низкий гемоглобин может привести к слабости, утомляемости и анемии.
Высокий уровень может повышать вязкость крови и нагрузку на сердце.
</p>

<h2>Что делать</h2>
<p>
Если показатель отклоняется от нормы, рекомендуется сдать дополнительные анализы
(ферритин, железо, витамин B12) и проконсультироваться с врачом.
</p>

<h2>Связанные показатели</h2>
<ul>
    <li>Ферритин</li>
    <li>Железо</li>
</ul>

